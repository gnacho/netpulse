/* merge profundo: I18N_EXTRA → I18N (las claves existentes se conservan) */
Object.entries(I18N_EXTRA).forEach(([lang, dict]) => {
  const target = I18N[lang] || (I18N[lang] = {})
  Object.entries(dict).forEach(([section, keys]) => {
    target[section] = Object.assign(target[section] || {}, keys)
  })
})

function t(path, vars) {
  const seg = path.split('.')
  let o = I18N[CURRENT]
  for (const s of seg) { o = o ? o[s] : undefined }
  if (o === undefined) { // fallback a EN
    o = I18N.en
    for (const s of seg) { o = o ? o[s] : undefined }
  }
  const out = o ?? path
  if (vars) return out.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? `{${k}}`)
  return out
}

/** Nombre localizado de un nodo del canon (routers/dispositivos/peers).
 *  La clave es el nombre canónico (ES); si no hay traducción en el idioma
 *  activo se devuelve el nombre canónico tal cual (para ES es el propio). */
function tName(name) {
  return I18N[CURRENT]?.topo?.names?.[name] || name
}

function applyLang(lang) {
  CURRENT = lang
  const meta = LANGS[lang]
  document.documentElement.lang = lang
  document.documentElement.dir = meta.dir
  try { localStorage.setItem(LANG_KEY, lang) } catch { /* modo privado */ }
  document.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(el.dataset.i18n)
  })
  document.querySelectorAll('[data-i18n-aria]').forEach(el => {
    el.setAttribute('aria-label', t(el.dataset.i18nAria))
  })
  document.querySelectorAll('[data-i18n-attr]').forEach(el => {
    const attr = el.dataset.i18nAttr
    const key = el.dataset.i18n
    if (attr && key) el.setAttribute(attr, t(key))
  })
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    el.innerHTML = t(el.dataset.i18nHtml)
  })
  // selector de idioma
  const sel = document.getElementById('langSelect')
  if (sel) sel.value = lang
  // re-render dinámicos
  if (typeof renderTicker === 'function') renderTicker()
  if (typeof renderAlerts === 'function') renderAlerts()
  if (typeof renderRouterNames === 'function') renderRouterNames()
  if (typeof renderTopoNames === 'function') renderTopoNames()
  if (typeof renderAdGuardTexts === 'function') renderAdGuardTexts()
  if (typeof renderShot === 'function') renderShot()
  if (typeof updateAppearancePanel === 'function') updateAppearancePanel()
}

function buildLangSelect() {
  const sel = document.getElementById('langSelect')
  if (!sel) return
  Object.entries(LANGS).forEach(([code, m]) => {
    const o = document.createElement('option')
    o.value = code
    o.textContent = `${m.flag} ${m.name}`
    sel.appendChild(o)
  })
  sel.value = CURRENT
  sel.addEventListener('change', () => applyLang(sel.value))
}

document.addEventListener('DOMContentLoaded', () => {
  buildLangSelect()
  applyLang(CURRENT)
})
